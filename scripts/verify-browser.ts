import { File } from 'node:buffer';
import { strict as assert } from 'node:assert';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { appKit, loadShellPlan, shellPlanFromState, shellRegistry, type ShellPlanFile } from '../src/framework/app-kit/plans';
import { createActionRegistry, dispatchActionEvent, runAction, validateActionBindings } from '../src/framework/actions';
import { AppDialog, AppMenubar, AppToolbar } from '../src/framework/app-kit/Chrome';
import { children, chooseLocalAdapter, createSampleAdapter } from '../src/framework/app-kit/browser';
(globalThis as any).File = File;
async function main() {
  for (const id of ['sidebar', 'split', 'columns', 'browser']) {
    const result = appKit.instantiate(id, { title: id });
    assert(result.ok);
    assert(loadShellPlan(JSON.parse(JSON.stringify(result.data))).ok);
  }
  assert(!loadShellPlan({ schema: 'paramorphic-shell/1', layout: 'columns', slots: [], widths: [], title: '' }).ok);
  const browser = appKit.instantiate('browser', {});
  assert(browser.ok && browser.plan.menus && browser.plan.dialogs);
  const file = JSON.parse(JSON.stringify(browser.data)) as ShellPlanFile;
  assert.equal(file.schema, 'paramorphic-shell/2');
  assert.deepEqual(file.morphs.map(m => m.name), ['shell.title', 'shell.layout', 'shell.menus', 'shell.toolbar', 'shell.dialogs', 'shell.actions']);
  assert(loadShellPlan(file).ok);
  assert(loadShellPlan(browser.plan).ok); // Legacy snapshot.
  const original = JSON.stringify(file.base);
  const edited = shellRegistry.removeAt(file.base, file.morphs, 4, {}, s => JSON.parse(JSON.stringify(s)));
  assert(edited.ok && edited.state.dialogs === undefined);
  assert.equal(JSON.stringify(file.base), original);
  const framed = shellRegistry.recaptureFrames(file.base, file.morphs, s => JSON.parse(JSON.stringify(s)));
  const reverted = shellRegistry.invertMorph(browser.plan, framed[4]);
  assert(reverted && reverted.dialogs === undefined && reverted.toolbar?.length === 2);
  assert(!loadShellPlan({ ...file, morphs: [...file.morphs, { name: 'shell.unknown', params: {} }] }).ok);
  assert(!loadShellPlan({ ...file, morphs: [{ name: 'shell.layout', params: { value: { layout: 'columns', slots: [], widths: [] } } }] }).ok);
  assert(!loadShellPlan({ ...file, morphs: 'invalid' }).ok);
  assert(!loadShellPlan({ ...browser.plan, actions: [{ id: 'sample', do: 'missing.operation', target: 'browser' }] }).ok);
  assert(!loadShellPlan({ ...browser.plan, actions: browser.plan.actions?.filter(a => a.id !== 'sample') }).ok);
  assert(!loadShellPlan({ ...browser.plan, actions: browser.plan.actions?.map(a => a.id === 'about' ? { ...a, target: 'missing' } : a) }).ok);
  let opened = '';
  assert((await runAction('about', browser.plan.actions!, { openDialog: target => { opened = target; } })).ok);
  assert.equal(opened, 'about');
  let invoked = '';
  assert((await runAction('sample', browser.plan.actions!, { useSample: target => { invoked = target; } })).ok);
  assert.equal(invoked, 'browser');
  assert(!(await runAction('open-folder', browser.plan.actions!, {})).ok);
  assert(!(await runAction('missing', browser.plan.actions!, {})).ok);
  const custom = createActionRegistry();
  custom.register({ name: 'custom.mark', validate: () => [], run: action => { invoked = String(action.value); } });
  const customPlan = { ...browser.plan, menus: [], toolbar: [], actions: [{ id: 'mark', do: 'custom.mark', value: 'ok' }] };
  assert(!loadShellPlan(customPlan).ok);
  assert(loadShellPlan(customPlan, custom).ok);
  assert(loadShellPlan(shellPlanFromState(customPlan), custom).ok);
  assert((await runAction('mark', customPlan.actions, {}, custom)).ok);
  assert.equal(invoked, 'ok');
  const shared = [{ id: 'select-node', do: 'selection.select', target: 'node-1' }, { id: 'navigate', do: 'navigation.open', target: 'folder-1' }, { id: 'update', do: 'state.set', target: 'selection', value: 42 }];
  assert((await runAction('select-node', shared, { select: target => { invoked = target; } })).ok && invoked === 'node-1');
  assert((await runAction('navigate', shared, { navigate: target => { invoked = target; } })).ok && invoked === 'folder-1');
  assert((await runAction('update', shared, { setState: (target, value) => { invoked = `${target}:${value}`; } })).ok && invoked === 'selection:42');
  assert(!(await runAction('bad', [{ id: 'bad', do: 'state.set', target: 'selection' }], {})).ok);
  const bindings = { 'cell.activate': 'select-node' };
  assert.equal(validateActionBindings(bindings, shared).length, 0);
  assert((await dispatchActionEvent('cell.activate', bindings, shared, { select: target => { invoked = target; } })).ok && invoked === 'node-1');
  assert.equal(validateActionBindings({ click: 'missing' }, shared).length, 1);
  assert(!(await dispatchActionEvent('missing', bindings, shared, {})).ok);
  assert(!loadShellPlan({ ...browser.plan, menus: [{ id: 'x', label: 'File', items: [{ id: '', label: 'Bad' }] }] }).ok);
  assert(!loadShellPlan({ ...browser.plan, dialogs: [{ id: 'x', title: '', message: '' }] }).ok);
  assert(!loadShellPlan({ ...browser.plan, toolbar: [{ id: 'x', label: 'One' }, { id: 'x', label: 'Two' }] }).ok);
  const menu = renderToStaticMarkup(React.createElement(AppMenubar, { menus: browser.plan.menus, onAction: () => {} }));
  assert(menu.includes('aria-label="Application menu"') && menu.includes('aria-expanded="false"') && menu.includes('File'));
  const toolbar = renderToStaticMarkup(React.createElement(AppToolbar, { items: browser.plan.toolbar ?? [], onAction: () => {} }));
  assert(toolbar.includes('aria-label="Application toolbar"') && toolbar.includes('Open local folder'));
  const dialog = renderToStaticMarkup(React.createElement(AppDialog, { open: false, title: 'About', onClose: () => {}, children: 'Description' }));
  assert(dialog.includes('<dialog') && dialog.includes('aria-labelledby=') && dialog.includes('About'));
  const demo = createSampleAdapter();
  const root = await demo.list(demo.root);
  assert.equal(root[0].label, 'Documents');
  const docs = await demo.list(root[0]);
  const notes = docs.find(n => n.label === 'Notes')!;
  const files = await demo.list(notes);
  assert.equal(await (await demo.read(files[0])).text(), 'Sample file: welcome.txt\n');
  assert.equal(children(files, 'missing').length, 0);
  const fakeFile = { kind: 'file', name: 'hello.txt', getFile: async () => new File(['hello'], 'hello.txt', { type: 'text/plain' }) };
  const folder = { kind: 'directory', name: 'Local', async *values() { yield fakeFile; } };
  (globalThis as any).window = { showDirectoryPicker: async () => folder };
  const local = await chooseLocalAdapter();
  const entries = await local.list(local.root);
  assert.equal(await (await local.read(entries[0])).text(), 'hello');
  (globalThis as any).window = {};
  await assert.rejects(chooseLocalAdapter(), /not supported/);
  console.log('Browser kit checks passed');
}
main().catch(e => { console.error(e); process.exitCode = 1; });
