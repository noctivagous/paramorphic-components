import { strict as assert } from 'node:assert';
import { cellIsSelected, clampGridSelection, initialGridSelection, selectGridCell, selectedCellCount } from '../src/framework/grid-selection';
import { loadPlan } from '../src/framework/plan';
import { readFileSync } from 'node:fs';
import '../src/framework/index';
const initial = initialGridSelection();
assert.equal(selectedCellCount(initial, 5, 4), 1);
const clicked = selectGridCell(initial, { q: 2, r: 1 }, 5, 4, 'range');
assert.equal(selectedCellCount(clicked, 5, 4), 1);
const dragged = selectGridCell(clicked, { q: 4, r: 3 }, 5, 4, 'range', 'extend');
assert.equal(selectedCellCount(dragged, 5, 4), 9);
assert(cellIsSelected(dragged, { q: 3, r: 2 }));
assert(!cellIsSelected(dragged, { q: 1, r: 2 }));
const reverse = selectGridCell(clicked, { q: -3, r: -2 }, 5, 4, 'range', 'extend');
assert.equal(selectedCellCount(reverse, 5, 4), 6);
const single = selectGridCell(clicked, { q: 4, r: 3 }, 5, 4, 'single', 'extend');
assert.equal(selectedCellCount(single, 5, 4), 1);
const added = selectGridCell(dragged, { q: 0, r: 0 }, 5, 4, 'multiple', 'add');
assert.equal(selectedCellCount(added, 5, 4), 10);
const overlap = selectGridCell(added, { q: 2, r: 1 }, 5, 4, 'multiple', 'add');
assert.equal(selectedCellCount(overlap, 5, 4), 10);
const resized = clampGridSelection(dragged, 3, 2);
assert.equal(selectedCellCount(resized, 3, 2), 1);
const plan = JSON.parse(readFileSync('apps/spreadsheet/morph-plans/spreadsheet.json', 'utf8'));
assert(loadPlan({ data: plan, errors: [] }, null).ok);
assert(!loadPlan({ data: { ...plan, interpretation: { ...plan.interpretation, grid: { ...plan.interpretation.grid, selection: { mode: 'unknown' } } } }, errors: [] }, null).ok);
console.log('Grid selection checks passed');
